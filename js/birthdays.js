window.BIRTHDAY_SCHEDULE = {
  10: 'shuki', 11: 'bobi', 12: 'laura', 1: 'pil', 2: 'gili', 3: 'junior',
  4: 'cooper', 5: 'micha', 6: 'bella',
  7: 'shuki', 8: 'bobi', 9: 'laura' // ← חסרים: ממתינים ל-3 כלבים נוספים מהעמותה
};

(function () {
  var q = parseInt(new URLSearchParams(location.search).get('month'), 10);
  var month = q >= 1 && q <= 12 ? q : new Date().getMonth() + 1;
  var slug = window.BIRTHDAY_SCHEDULE[month];
  var dog = window.LOO_DOGS[slug];
  if (!dog) return;
  window.BIRTHDAY_DOG = Object.assign({ slug: slug }, dog);
  function fill() {
    document.querySelectorAll('[data-bd-name]').forEach(function (el) { el.textContent = dog.name; });
    document.querySelectorAll('[data-bd-img]').forEach(function (el) { el.src = dog.img; el.alt = dog.name + ' חוגג/ת יום הולדת'; });
    document.querySelectorAll('[data-bd-story]').forEach(function (el) { el.textContent = dog.story; });
    document.querySelectorAll('[data-bd-tagline]').forEach(function (el) { el.textContent = dog.tagline; });
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fill); else fill();
})();
