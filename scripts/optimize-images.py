#!/usr/bin/env python3
"""Compress site photos and make a small copy for phones (13.11, SEO/speed).

For every JPG in public/assets/img: re-save at quality 80 (progressive) if that saves 10%+, cap the long side at
1400px, and write <name>-sm.jpg (long side 700px). src/lib/imgVariants.ts lists the photos that have a -sm copy (with widths),
so <img srcSet> only points at files that exist. Run after adding photos: python3 scripts/optimize-images.py
"""
from pathlib import Path
from PIL import Image, ImageOps

DIR = Path('public/assets/img')
OUT = Path('src/lib/imgVariants.ts')
done, saved = [], 0
for f in sorted(DIR.glob('*.jpg')):
    if f.stem.endswith('-sm'):
        continue
    im = ImageOps.exif_transpose(Image.open(f)).convert('RGB')
    before = f.stat().st_size
    if max(im.size) > 1400:
        im.thumbnail((1400, 1400), Image.LANCZOS)
    tmp = f.with_suffix('.tmp.jpg')
    im.save(tmp, 'JPEG', quality=80, optimize=True, progressive=True)
    if tmp.stat().st_size < before * 0.9:
        saved += before - tmp.stat().st_size
        tmp.replace(f)
    else:
        tmp.unlink()
    if max(im.size) > 760:
        sm = im.copy()
        sm.thumbnail((700, 700), Image.LANCZOS)
        sm.save(f.with_name(f.stem + '-sm.jpg'), 'JPEG', quality=76, optimize=True, progressive=True)
        done.append((f'/assets/img/{f.name}', sm.size[0], im.size[0]))
rows = ''.join(f'  ["{p}", [{a}, {b}]],\n' for p, a, b in done)
OUT.write_text('// Generated by scripts/optimize-images.py: photos with a -sm.jpg copy, as [path, [small width, full width]].\n'
               f'export const SMALL = new Map<string, [number, number]>([\n{rows}])\n')
print(f'{len(done)} small copies, originals {saved // 1024} KB smaller')
